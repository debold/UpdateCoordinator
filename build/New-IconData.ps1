<#
.SYNOPSIS
    Turns the Lucide icons in assets/icons/lucide into the C# table the dashboard renders them from.

.DESCRIPTION
    The dashboard shows icons as inline SVG (no extra requests, no script, CSP-safe). The SVG files are copied unchanged
    from the lucide-static package (ISC license, see assets/icons/lucide/LICENSE); this script keeps only their inner
    elements and writes src/SUSyphos.Server/Components/Shared/IconData.g.cs. To add an icon, copy its SVG from
    lucide-static into assets/icons/lucide, run this script and commit both.
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$source = Join-Path $root 'assets\icons\lucide'
$target = Join-Path $root 'src\SUSyphos.Server\Components\Shared\IconData.g.cs'

$entries = foreach ($file in Get-ChildItem $source -Filter '*.svg' | Sort-Object Name) {
    $xml = [xml](Get-Content $file.FullName -Raw)
    $inner = ($xml.svg.ChildNodes | Where-Object { $_.NodeType -eq 'Element' } | ForEach-Object {
        $_.OuterXml -replace ' xmlns="http://www.w3.org/2000/svg"', ''
    }) -join ''
    if ($inner -notmatch '^(<(path|circle|rect|line|polyline|polygon|ellipse)( [a-z0-9-]+="[^"<>]*")* ?/>)+$') {
        throw "$($file.Name) contains unexpected markup."
    }

    "        [""$($file.BaseName)""] = ""$($inner.Replace('"', '\"'))"","
}

$code = @"
// <auto-generated>Written by build/New-IconData.ps1 from assets/icons/lucide (lucide-static, ISC license). Do not edit.</auto-generated>
using System.Collections.Frozen;

namespace SUSyphos.Server.Components.Shared;

public static class IconData
{
    /// <summary>Inner SVG elements of each icon (24 x 24, stroke icons).</summary>
    public static readonly FrozenDictionary<string, string> Elements = new Dictionary<string, string>(StringComparer.Ordinal)
    {
$($entries -join "`n")
    }.ToFrozenDictionary(StringComparer.Ordinal);
}
"@
[IO.File]::WriteAllText($target, $code.Replace("`r`n", "`n"), (New-Object Text.UTF8Encoding($false)))
Write-Host "Wrote $target"
